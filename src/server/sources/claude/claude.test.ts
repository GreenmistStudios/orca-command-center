import { mkdtempSync, rmSync, writeFileSync, appendFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import path from 'node:path'
import { afterEach, beforeEach, describe, expect, it } from 'vitest'
import type { HarnessSource } from '../../types.js'
import { OPAQUE, SECRET, appendJsonl, claudeLines, makeSource, until, writeJsonl, type Made } from '../../../../test/fixtures/jsonl-harnesses.js'
import { cleanClaudePrompt, createClaudeSource } from './index.js'

let tmp: string
const made: HarnessSource[] = []
beforeEach(() => {
  tmp = mkdtempSync(path.join(tmpdir(), 'claude-'))
})
afterEach(async () => {
  for (const s of made.splice(0)) await s.stop()
  rmSync(tmp, { recursive: true, force: true })
})

const CWD = '/Users/me/src/app'
const PROJ = '-Users-me-src-app'
const ROOT_ID = '11111111-2222-4333-8444-555555555555'
const LIVE_ID = '66666666-7777-4888-9999-000000000000'

function make(dir: string | null = tmp): Made {
  const m = makeSource(createClaudeSource, { claudeDir: dir })
  made.push(m.src)
  return m
}

const sessionFile = (id: string) => path.join(tmp, 'projects', PROJ, `${id}.jsonl`)

function seedFinished(t0 = Date.now() - 60_000): string {
  const L = claudeLines(ROOT_ID, CWD, t0)
  return writeJsonl(sessionFile(ROOT_ID), [
    { type: 'summary', summary: 'Old summary', leafUuid: 'x' },
    L.user('<command-name>/review</command-name>\n<command-args>PR 12</command-args>'),
    L.user('Caveat: The messages below were generated by the user while running local commands.', { isMeta: true }),
    L.assistant('msg_1', [{ type: 'thinking', thinking: 'Plan the change', signature: OPAQUE }], { stop: null }),
    L.assistant('msg_1', [{ type: 'tool_use', id: 'toolu_bash', name: 'Bash', input: { command: `GH_TOKEN=${SECRET} gh pr view 12`, description: 'View PR' } }], { stop: 'tool_use' }),
    L.toolResult('toolu_bash', `token ${SECRET}\nhttps://github.com/acme/app/pull/12`),
    L.assistant('msg_2', [{ type: 'tool_use', id: 'toolu_edit', name: 'Edit', input: { file_path: `${CWD}/src/a.ts`, old_string: 'a', new_string: 'b' } }], { stop: 'tool_use' }),
    L.toolResult('toolu_edit', 'ok', { toolUseResult: { filePath: `${CWD}/src/a.ts`, structuredPatch: [{ oldStart: 3, oldLines: 2, newStart: 3, newLines: 3, lines: [' ctx', '-a', '+b', '+c'] }] } }),
    L.assistant('msg_3', [{ type: 'tool_use', id: 'toolu_write', name: 'Write', input: { file_path: 'src/new.ts', content: 'x\ny\n' } }], { stop: 'tool_use' }),
    L.toolResult('toolu_write', 'created', { toolUseResult: { type: 'create', filePath: `${CWD}/src/new.ts` } }),
    L.assistant('msg_4', [{ type: 'tool_use', id: 'toolu_todo', name: 'TodoWrite', input: { todos: [{ content: 'Ship it', status: 'in_progress', activeForm: 'Shipping' }, { content: 'Test it', status: 'pending' }] } }], { stop: 'tool_use' }),
    L.toolResult('toolu_todo', 'ok'),
    L.assistant('msg_5', [{ type: 'tool_use', id: 'toolu_mcp', name: 'mcp__github__get_issue', input: { number: 12 } }], { stop: 'tool_use' }),
    L.toolResult('toolu_mcp', 'not found', {}, true),
    L.raw({ type: 'user', isSidechain: true, message: { role: 'user', content: 'SIDECHAIN-SHOULD-NOT-APPEAR' } }),
    L.assistant('msg_6', [{ type: 'text', text: 'Done. See https://github.com/acme/app/pull/12' }], { stop: 'end_turn', usage: { input_tokens: 1, output_tokens: 2, cache_read_input_tokens: 3, cache_creation_input_tokens: 4 } }),
    { type: 'ai-title', aiTitle: 'Review PR 12', sessionId: ROOT_ID },
  ])
}

describe('cleanClaudePrompt', () => {
  it('unwraps commands and drops injected wrappers', () => {
    expect(cleanClaudePrompt('<command-message>review</command-message>\n<command-name>/review</command-name>\n<command-args>12</command-args>')).toBe('/review 12')
    expect(cleanClaudePrompt('<local-command-stdout>ok</local-command-stdout>')).toBeNull()
    expect(cleanClaudePrompt('hi <system-reminder>secret ctx</system-reminder>')).toBe('hi')
  })
})

describe('claude source', () => {
  it('reports disabled / missing', async () => {
    const a = make(null)
    await a.src.start()
    expect(a.src.health().status).toBe('disabled')
    const b = make(path.join(tmp, 'nope'))
    await b.src.start()
    expect(b.src.health().status).toBe('missing')
    expect(b.src.listSessions(0)).toEqual([])
  })

  it('derives a finished session: title, model, tokens, state, tools, files, todos', async () => {
    seedFinished()
    const { src } = make()
    await src.start()
    expect(src.health()).toMatchObject({ id: 'claude', status: 'ok', version: '2.0.30' })
    const s = src.getSession(ROOT_ID)!
    expect(s).toMatchObject({
      harness: 'claude',
      parentId: null,
      title: 'Review PR 12',
      agent: 'claude',
      model: { providerId: 'anthropic', modelId: 'claude-sonnet-4-5-20250929' },
      directory: CWD,
      transcriptState: 'done',
      current: null,
      lastPrompt: '/review PR 12',
    })
    // usage counted once per message id (msg_1 has two lines)
    expect(s.tokens).toEqual({ input: 51, output: 102, reasoning: 0, cacheRead: 503, cacheWrite: 29 })
    expect(s.facts).toEqual(expect.arrayContaining([{ label: 'Branch', value: 'main' }]))

    const events = src.getActivity([ROOT_ID], { limit: 100 }).events
    const bash = events.find((e) => e.tool?.name === 'Bash')!
    expect(bash).toMatchObject({ kind: 'tool', status: 'completed', tool: { category: 'shell' } })
    expect(bash.links).toContain('https://github.com/acme/app/pull/12')
    expect(events.find((e) => e.tool?.name === 'mcp__github__get_issue')).toMatchObject({ kind: 'mcp', status: 'error', tool: { mcpServer: 'github', displayName: 'get_issue' } })
    expect(events.find((e) => e.kind === 'thinking')?.summary).toBe('Plan the change')
    expect(events.map((e) => e.kind)).toContain('todo')

    const blob = JSON.stringify([src.listSessions(0), events, events.map((e) => src.getPart(e.id)), src.getTranscript(ROOT_ID, { limit: 100 })])
    expect(blob).not.toContain(SECRET)
    expect(blob).not.toContain(OPAQUE)
    expect(blob).not.toContain('SIDECHAIN-SHOULD-NOT-APPEAR')
    expect(blob).not.toContain('Caveat: The messages')

    const changes = src.getFileChanges([ROOT_ID])
    expect(changes.map((c) => [c.relPath, c.kind, c.additions, c.deletions])).toEqual([
      ['src/a.ts', 'edit', 2, 1],
      ['src/new.ts', 'create', 2, 0],
    ])
    const editDiff = src.getDiff(changes[0]!.id)!
    expect(editDiff).toMatchObject({ format: 'unified' })
    expect(editDiff.text).toContain('@@ -3,2 +3,3 @@')
    expect(src.getDiff(changes[1]!.id)).toMatchObject({ format: 'new-file', text: 'x\ny\n' })

    expect(src.getTodos(ROOT_ID).map((t) => [t.content, t.status])).toEqual([
      ['Ship it', 'in_progress'],
      ['Test it', 'pending'],
    ])
    const c = src.getCounters(ROOT_ID)
    expect(c).toMatchObject({ tools: 5, toolErrors: 1, mcpCalls: 1, fileChanges: 2, thinking: 1, steps: 6 })
    const tr = src.getTranscript(ROOT_ID, { limit: 100 })
    expect(tr.messages[0]).toMatchObject({ role: 'user' })
    expect(tr.messages.some((m) => m.role === 'assistant' && m.tokens !== null)).toBe(true)
    expect(src.getToolStats([ROOT_ID]).map((t) => t.name)).toContain('Bash')
  })

  it('working / waiting / error states and current activity', async () => {
    const L = claudeLines(LIVE_ID, CWD, Date.now() - 5000)
    const file = writeJsonl(sessionFile(LIVE_ID), [L.user('Run the tests'), L.assistant('m1', [{ type: 'tool_use', id: 't1', name: 'Bash', input: { command: 'npm test' } }], { stop: 'tool_use' })])
    const { src, updates } = make()
    await src.start()
    expect(src.getSession(LIVE_ID)).toMatchObject({ transcriptState: 'working', current: { label: 'Bash', detail: 'npm test' } })

    appendJsonl(file, [L.toolResult('t1', 'ok'), L.assistant('m2', [{ type: 'tool_use', id: 't2', name: 'AskUserQuestion', input: { questions: [{ question: 'Ship?' }] } }], { stop: 'tool_use' })])
    await until(() => src.getSession(LIVE_ID)?.transcriptState === 'waiting')
    await until(() => updates.some((u) => u.type === 'activity'))

    appendJsonl(file, [L.toolResult('t2', 'yes'), L.assistant('m3', [{ type: 'text', text: 'Credit balance too low' }], {}), ])
    const last = { ...L.assistant('m4', [{ type: 'text', text: 'API Error: 529 overloaded' }], { stop: 'stop_sequence' }), isApiErrorMessage: true }
    appendJsonl(file, [last])
    await until(() => src.getSession(LIVE_ID)?.transcriptState === 'error')
    const sess = updates.filter((u) => u.type === 'sessions')
    expect(sess.length).toBeGreaterThan(0)
  })

  it('buffers a partial trailing line until it is complete', async () => {
    const L = claudeLines(LIVE_ID, CWD, Date.now() - 5000)
    const file = writeJsonl(sessionFile(LIVE_ID), [L.user('hello')])
    const { src } = make()
    await src.start()
    const line = JSON.stringify(L.assistant('m1', [{ type: 'text', text: 'partial reply' }], { stop: 'end_turn' }))
    appendFileSync(file, line.slice(0, 40))
    await new Promise((r) => setTimeout(r, 120))
    expect(src.getSession(LIVE_ID)?.lastMessage).toBeNull()
    appendFileSync(file, line.slice(40) + '\n')
    await until(() => src.getSession(LIVE_ID)?.lastMessage === 'partial reply')
    expect(src.getSession(LIVE_ID)?.transcriptState).toBe('done')
  })

  it('links subagent transcripts to the spawning Task call', async () => {
    const t0 = Date.now() - 10_000
    const L = claudeLines(ROOT_ID, CWD, t0)
    const parent = writeJsonl(sessionFile(ROOT_ID), [
      L.user('Investigate'),
      L.assistant('m1', [{ type: 'tool_use', id: 'toolu_task', name: 'Task', input: { description: 'Find the bug', prompt: 'Look for the crash in src/a.ts', subagent_type: 'Explore' } }], { stop: 'tool_use' }),
    ])
    const C = claudeLines(ROOT_ID, CWD, t0 + 2000)
    const childFile = writeJsonl(path.join(tmp, 'projects', PROJ, ROOT_ID, 'subagents', 'agent-a1b2c3.jsonl'), [
      { ...C.user('Look for the crash in src/a.ts'), isSidechain: true, agentId: 'a1b2c3' },
      { ...C.assistant('c1', [{ type: 'tool_use', id: 'toolu_grep', name: 'Grep', input: { pattern: 'crash' } }], { stop: 'tool_use' }), isSidechain: true },
    ])
    const childId = `${ROOT_ID}.agent-a1b2c3`
    const { src } = make()
    await src.start()
    const child = src.getSession(childId)!
    expect(child).toMatchObject({ parentId: ROOT_ID, agent: 'Explore', title: 'Find the bug', spawn: { parentSessionId: ROOT_ID, callId: 'toolu_task', subagentType: 'Explore', status: 'running' } })
    expect(src.getChildren(ROOT_ID).map((s) => s.id)).toEqual([childId])
    const task = src.getActivity([ROOT_ID], { limit: 50 }).events.find((e) => e.kind === 'subagent')!
    expect(task).toMatchObject({ childSessionId: childId, title: 'Explore · Find the bug' })

    appendJsonl(childFile, [{ ...C.assistant('c2', [{ type: 'text', text: 'Found it' }], { stop: 'end_turn' }), isSidechain: true }])
    appendJsonl(parent, [L.toolResult('toolu_task', [{ type: 'text', text: 'Found it' }], { toolUseResult: { status: 'completed', agentId: 'a1b2c3', totalDurationMs: 100 } })])
    await until(() => src.getSession(childId)?.spawn?.status === 'completed')
    expect(src.listSessions(0).map((s) => s.id).sort()).toEqual([ROOT_ID, childId].sort())
  })

  it('a truncated file resets the cursor and re-reads', async () => {
    const file = seedFinished(Date.now() - 5000)
    const { src, updates } = make()
    await src.start()
    const L = claudeLines(ROOT_ID, CWD, Date.now())
    writeFileSync(file, JSON.stringify(L.user('fresh start')) + '\n')
    await until(() => updates.some((u) => u.type === 'reset'))
    await until(() => src.getSession(ROOT_ID)?.lastPrompt === 'fresh start')
  })
})
